  /** สร้างรายการข้อสอบสำหรับการทำครั้งใหม่ */
  async build(user, id, settings) {
    const p = Exams.parse(id);
    const progress = { examId: id, qids: [], answers: {}, flags: [], current: 0, choiceOrder: null,
      timed: false, remaining: 0, elapsed: 0, startedAt: Date.now() };

    if (p.type === 'subject') {
      const bank = await Repo.getBank(p.subject);
      const hasSets = bank.some((q) => q.set != null);
      if (hasSets) {
        progress.qids = bank.filter((q) => (q.set || 1) === p.set).map((q) => q.id);
      } else {
        const size = settings.setSize;
        progress.qids = bank.slice((p.set - 1) * size, p.set * size).map((q) => q.id);
      }
    } else if (p.type === 'final_set') {
      const bank = await Repo.getBank('final');
      progress.qids = bank.filter((q) => (q.set || 1) === p.set).map((q) => q.id);
      if (settings.shuffleChoicesFinal) {
        const map = await Repo.getQuestionMap();
        progress.choiceOrder = {};
        progress.qids.forEach((qid) => { if (map[qid]) progress.choiceOrder[qid] = shuffle(map[qid].choices.map((_, i) => i)); });
      }
    } else if (p.type === 'review') {
      const wrong = await Repo.getWrong(user.id);
      const map = await Repo.getQuestionMap();
      progress.qids = shuffle(Object.keys(wrong).filter((k) => map[k])).slice(0, 50);
    } else if (p.type === 'bookmark') {
      const map = await Repo.getQuestionMap();
      progress.qids = (await Repo.getBookmarks(user.id)).filter((k) => map[k]);
    } else if (p.type === 'final') {
      progress.qids = await Exams.pickFinal(user, settings);
      if (settings.shuffleChoicesFinal) {
        const map = await Repo.getQuestionMap();
        progress.choiceOrder = {};
        progress.qids.forEach((qid) => { if (map[qid]) progress.choiceOrder[qid] = shuffle(map[qid].choices.map((_, i) => i)); });
      }
    }
    return progress;
  },

  /** คละข้อสอบชุดรวม: ดึงจากคลังชุดรวมเฉพาะ 'bank:final' (หรือสุ่มกระจาย 5 เรื่องถ้าไม่มี) */
  async pickFinal(user, settings) {
    const finalBank = await Repo.getBank('final');
    if (finalBank && finalBank.length > 0) {
      let seen = new Set(await Repo.getSeen(user.id));
      const all = finalBank.map((q) => q.id);
      let fresh = shuffle(all.filter((x) => !seen.has(x)));
      const want = Math.min(settings.finalCount || 100, finalBank.length);
      if (fresh.length < want) {
        all.forEach((x) => seen.delete(x));
        fresh = shuffle(all);
      }
      const picked = fresh.slice(0, want);
      picked.forEach((x) => seen.add(x));
      await Repo.saveSeen(user.id, [...seen]);
      return picked;
    }

    const target = settings.finalCount;
    const banks = {};
    for (const s of SUBJECTS) banks[s.id] = await Repo.getBank(s.id);
    const totalAvail = Object.values(banks).reduce((n, b) => n + b.length, 0);
    const want = Math.min(target, totalAvail);

    // โควตาต่อเรื่อง (เท่า ๆ กันตาม Blueprint แล้วเกลี่ยส่วนที่ขาด)
    const quota = {};
    let remain = want;
    const ids = SUBJECTS.map((s) => s.id);
    ids.forEach((sid) => { quota[sid] = 0; });
    while (remain > 0) {
      const open = ids.filter((sid) => quota[sid] < banks[sid].length);
      if (!open.length) break;
      const share = Math.max(1, Math.floor(remain / open.length));
      for (const sid of open) {
        if (remain <= 0) break;
        const add = Math.min(share, banks[sid].length - quota[sid], remain);
        quota[sid] += add; remain -= add;
      }
    }

    let seen = new Set(await Repo.getSeen(user.id));
    const picked = [];
    for (const sid of ids) {
      const all = banks[sid].map((q) => q.id);
      let fresh = shuffle(all.filter((x) => !seen.has(x)));
      if (fresh.length < quota[sid]) {
        // ข้อใหม่ไม่พอ: เอาข้อใหม่ทั้งหมด + รีเซ็ตรอบของเรื่องนี้ แล้วสุ่มเพิ่มจากข้อเก่า
        const need = quota[sid] - fresh.length;
        all.forEach((x) => seen.delete(x));
        const old = shuffle(all.filter((x) => !fresh.includes(x))).slice(0, need);
        fresh = fresh.concat(old);
      }
      picked.push(...fresh.slice(0, quota[sid]));
    }
    picked.forEach((x) => seen.add(x));
    await Repo.saveSeen(user.id, [...seen]);
    return shuffle(picked);
  }
